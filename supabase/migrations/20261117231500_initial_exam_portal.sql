-- CDLU Examination Portal schema for Supabase/PostgreSQL.
-- Run in the Supabase SQL Editor or with the Supabase CLI.
-- Password hashes are managed by the Express backend; never insert plaintext passwords.

create table if not exists public.colleges (
  id bigint generated by default as identity primary key,
  code text not null unique,
  name text not null,
  city text not null default 'Sirsa',
  state text not null default 'Haryana',
  email text,
  phone text,
  status text not null default 'active',
  created_at timestamptz not null default now()
);

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  username text not null unique,
  password text not null,
  role text not null check (role in ('super_admin', 'college_admin', 'examiner', 'student')),
  name text not null,
  email text,
  phone text,
  college_id bigint references public.colleges(id) on delete set null,
  course text,
  semester text,
  status text not null default 'active' check (status in ('active', 'deactivated', 'locked')),
  created_at timestamptz not null default now()
);

create table if not exists public.exams (
  id bigint generated by default as identity primary key,
  code text not null unique,
  title text not null,
  subject text not null,
  course text not null,
  semester text not null,
  duration_minutes integer not null default 30 check (duration_minutes > 0),
  total_marks integer not null default 50 check (total_marks >= 0),
  passing_marks integer not null default 20 check (passing_marks >= 0),
  instructions text,
  college_id bigint references public.colleges(id) on delete cascade,
  start_window timestamptz,
  end_window timestamptz,
  is_active smallint not null default 1 check (is_active in (0, 1)),
  created_at timestamptz not null default now(),
  check (start_window is null or end_window is null or end_window > start_window)
);

create table if not exists public.questions (
  id bigint generated by default as identity primary key,
  exam_id bigint not null references public.exams(id) on delete cascade,
  question_number integer not null,
  question_text text not null,
  option_a text not null,
  option_b text not null,
  option_c text not null,
  option_d text not null,
  correct_option text not null check (correct_option in ('A', 'B', 'C', 'D')),
  marks integer not null default 2 check (marks >= 0),
  explanation text
);

create table if not exists public.student_exam_attempts (
  id bigint generated by default as identity primary key,
  student_id bigint not null references public.users(id) on delete cascade,
  exam_id bigint not null references public.exams(id) on delete cascade,
  server_start_time bigint not null,
  server_deadline bigint not null,
  server_submit_time bigint,
  status text not null default 'in_progress'
    check (status in ('in_progress', 'submitted', 'auto_submitted', 'locked')),
  is_locked smallint not null default 0 check (is_locked in (0, 1)),
  total_questions integer not null default 0,
  correct_answers integer not null default 0,
  incorrect_answers integer not null default 0,
  unanswered integer not null default 0,
  total_marks_obtained double precision not null default 0,
  max_possible_marks double precision not null default 0,
  time_taken_seconds integer not null default 0,
  ip_address text,
  user_agent text,
  created_at timestamptz not null default now(),
  unique (student_id, exam_id)
);

create table if not exists public.student_answers (
  id bigint generated by default as identity primary key,
  attempt_id bigint not null references public.student_exam_attempts(id) on delete cascade,
  question_id bigint not null references public.questions(id) on delete cascade,
  selected_option text check (selected_option is null or selected_option in ('A', 'B', 'C', 'D')),
  is_marked_review smallint not null default 0 check (is_marked_review in (0, 1)),
  is_correct smallint not null default 0 check (is_correct in (0, 1)),
  marks_awarded double precision not null default 0,
  updated_at bigint not null,
  unique (attempt_id, question_id)
);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  attempt_id bigint,
  student_id bigint,
  event_type text not null,
  details text,
  "timestamp" bigint not null
);

create index if not exists users_college_role_idx
  on public.users (college_id, role);
create index if not exists exams_college_course_active_idx
  on public.exams (college_id, course, is_active);
create index if not exists questions_exam_number_idx
  on public.questions (exam_id, question_number);
create index if not exists attempts_exam_status_idx
  on public.student_exam_attempts (exam_id, status);
create index if not exists attempts_deadline_unlocked_idx
  on public.student_exam_attempts (server_deadline)
  where is_locked = 0;
create index if not exists answers_question_idx
  on public.student_answers (question_id);
create index if not exists audit_logs_attempt_idx
  on public.audit_logs (attempt_id);
create index if not exists audit_logs_student_idx
  on public.audit_logs (student_id);

-- Browser clients must not access these tables directly. The trusted backend
-- will need to use Supabase's service role or a restricted server-side DB role.
alter table public.colleges enable row level security;
alter table public.users enable row level security;
alter table public.exams enable row level security;
alter table public.questions enable row level security;
alter table public.student_exam_attempts enable row level security;
alter table public.student_answers enable row level security;
alter table public.audit_logs enable row level security;

revoke all on table
  public.colleges,
  public.users,
  public.exams,
  public.questions,
  public.student_exam_attempts,
  public.student_answers,
  public.audit_logs
from anon, authenticated;

grant select, insert, update, delete on table
  public.colleges,
  public.users,
  public.exams,
  public.questions,
  public.student_exam_attempts,
  public.student_answers,
  public.audit_logs
to service_role;

grant usage, select on all sequences in schema public to service_role;
